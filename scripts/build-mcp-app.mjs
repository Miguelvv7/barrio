/**
 * Bundles src/mcp-app into ONE self-contained HTML file (Alexa+ requires inlined dependencies) and
 * writes it, with a content hash for the versioned ui:// URI, to src/lib/mcp/app-html.generated.ts.
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { build } from "esbuild";

const result = await build({
  entryPoints: [new URL("../src/mcp-app/card.ts", import.meta.url).pathname],
  bundle: true,
  minify: true,
  format: "iife",
  target: ["chrome100", "safari15"],
  write: false,
  legalComments: "none",
});
const js = result.outputFiles[0].text.replace(/<\/script/gi, "<\\/script");
const css = readFileSync(new URL("../src/mcp-app/card.css", import.meta.url), "utf8").replace(/\s+/g, " ");
const html = `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Barrio</title><style>${css}</style></head><body><div id="stage"></div><script>${js}</script></body></html>`;
const hash = createHash("sha256").update(html).digest("hex").slice(0, 10);
writeFileSync(
  new URL("../src/lib/mcp/app-html.generated.ts", import.meta.url),
  `// Generated by scripts/build-mcp-app.mjs — do not edit. Source: src/mcp-app/.\nexport const APP_HTML = ${JSON.stringify(html)};\nexport const APP_HASH = ${JSON.stringify(hash)};\n`,
);
console.log(`MCP App built: ${(html.length / 1024).toFixed(1)} KB, hash ${hash}`);
